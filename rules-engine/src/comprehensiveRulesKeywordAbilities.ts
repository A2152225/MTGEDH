const ABILITY_SET = new Set(COMPREHENSIVE_RULES_KEYWORD_ABILITIES);

/** A 702 keyword, a numbered annihilator, or a "[quality]walk" landwalk form. */
export function isGrantableKeywordAbility(name: string): boolean {
  const text = String(name || '').trim().toLowerCase();
  if (!text) return false;
  if (ABILITY_SET.has(text)) return true;
  if (/^annihilator \d+$/.test(text)) return true;
  if (/^(?:nonbasic |snow |artifact |legendary )?[a-z]+walk$/.test(text) && text !== 'walk') return true;
  return false;
}

export function isComprehensiveRulesKeywordAbility(name: string): boolean {
  return ABILITY_SET.has(String(name || '').trim().toLowerCase());
}
