for (const t of samples) {
  const ir = parseOracleTextToIR(t, 'Test');
  const gaps: string[] = [];
  for (const a of ir.abilities || []) {
    for (const s of a.steps || []) collectGaps(s).forEach((g) => gaps.push(g));
  }
  if (gaps.length) {
    fail++;
    console.log(`FAIL [${gaps[0].slice(0, 70)}]`);
  }
}
